def _split_row(row: str) -> tuple[str, str, str | None]:
    """`LANE=PATH[:MESSAGE]` -> lane, path, message (the path ends at the first colon)."""
    lane, sep, rest = row.partition("=")
    path, colon, message = rest.partition(":")
    if not sep or not lane.strip() or not path.strip() or (colon and not message.strip()):
        raise LandError("land.arguments", f"--patch expects LANE=PATH[:MESSAGE], got {row!r}")
    return lane, path, message.strip() if colon else None


def parse_patches(rows: Sequence[str]) -> list[tuple[str, Path]]:
    """`LANE=PATH[:MESSAGE]` rows, in order; lane names are unique."""
    patches: list[tuple[str, Path]] = []
    for row in rows:
        lane, path, _ = _split_row(row)
        if any(lane == seen for seen, _ in patches):
            raise LandError("land.arguments", f"lane {lane} is given twice")
        patches.append((lane, Path(path).expanduser().resolve()))
    return patches


def parse_messages(rows: Sequence[str]) -> dict[str, str]:
    """Lane -> the explicit commit message given as `LANE=PATH:MESSAGE`."""
    found = {}
    for row in rows:
        lane, _, message = _split_row(row)
        if message:
            found[lane] = message
    return found


def sentence_list(names: Sequence[str]) -> str:
    return ", ".join(names[:-1]) + " and " + names[-1] if len(names) > 1 else "".join(names)


def top_dirs(files: Sequence[str]) -> list[str]:
    """The source directories a commit touches: the first directory below src/ of each source file, sorted, case-folded
    once (headers, versions/ and generated files are not where a function was matched)."""
    found: dict[str, str] = {}
    for name in files:
        parts = name.split("/")
        if parts[0] == "src" and len(parts) > 2:
            found.setdefault(parts[1].casefold(), parts[1])
    return [found[key] for key in sorted(found)]


def commit_message(
    marker: str,
    names: Sequence[str],
    dirs: Sequence[str],
    limit: int,
    accept: Callable[[str, str | None], bool] | None = None,
) -> tuple[str, str | None]:
    """The project convention as (subject, body): "Fix N <marker> stand-ins in <dirs> by matching <names> as C" when it
    fits `limit`, else "... by matching C" with the dirs trimmed ("A, B and 3 more dirs", "5 dirs", none) and the full
    function list as the body paragraph. `accept(subject, body)` is the tree's own verdict on a candidate (its
    commit-msg hook): a candidate it refuses, e.g. a directory the hook bans by name, gives way to the next."""
    count = len(names)
    accepted = accept or (lambda subject, body: True)
    head = f"Fix {count} {marker} stand-in{'s' if count > 1 else ''}"
    full = f"{head}{f' in {sentence_list(dirs)}' if dirs else ''} by matching {sentence_list(names)} as C"
    if len(full) <= limit and accepted(full, None):
        return full, None
    body = f"Matched as C: {', '.join(names)}"
    options = [sentence_list(dirs)]
    for keep in range(len(dirs) - 1, 0, -1):
        more = len(dirs) - keep
        options.append(f"{', '.join(dirs[:keep])} and {more} more dir{'s' if more > 1 else ''}")
    options.append(f"{len(dirs)} dirs" if len(dirs) > 1 else "")
    for where in options:
        subject = f"{head}{f' in {where}' if where else ''} by matching C"
        if len(subject) <= limit and accepted(subject, body):
            return subject, body
    return head[:limit].rstrip(), body


def evidence_settings(profile: Profile, given: Any) -> dict[str, Any] | None:
    """`land.evidence` (absent: the gate is off): suffixes of the C sources it reads, the guard and stand-in macros,
    the header paths and ROM globs that key its cache, the seconds past which a measure is flagged."""
    if given is None:
        return None
    unknown = (
        set(given) - {"suffixes", "guard", "stand_in", "headers", "roms", "slow_seconds", "provenance", "names"}
        if isinstance(given, dict)
        else {"?"}
    )
    if unknown or not isinstance(given, dict):
        raise LandError(
            "config.schema", f"{profile.source_file}:land.evidence: expected an object; unknown {sorted(unknown)}"
        )
    return {
        "suffixes": tuple(s.lower() for s in given.get("suffixes", [".c", ".cpp"])),
        "guard": str(given.get("guard", "NON_MATCHING")),
        "stand_in": str(given.get("stand_in", "INCLUDE_ASM")),
        "headers": list(given.get("headers", ["include"])),
        "roms": list(given.get("roms", [])),
        "slow_seconds": float(given.get("slow_seconds", 60)),
        "provenance": provenance_settings(profile, given.get("provenance")),
        "names": names_settings(profile, given.get("names")),
    }


def provenance_settings(profile: Profile, given: Any) -> dict[str, Any] | None:
    """`land.evidence.provenance` (absent: off): `tries`, the Recipe tries streams a changed body must appear in
    (relative paths resolve against the profile's project; default `.unbake/recipe/tries.jsonl`)."""
    if given is None:
        return None
    if not isinstance(given, dict) or set(given) - {"tries"}:
        raise LandError("config.schema", f"{profile.source_file}:land.evidence.provenance: expected {{tries: [...]}}")
    return {"tries": [str(t) for t in given.get("tries", [".unbake/recipe/tries.jsonl"])]}


def names_settings(profile: Profile, given: Any) -> list[dict[str, str]]:
    """`land.evidence.names.rules` (absent: none): the machine-generated leftovers a changed body may not add, each
    {id, pattern (regex over a code line), hint}."""
    if given is None:
        return []
    rules = given.get("rules") if isinstance(given, dict) and set(given) <= {"rules"} else None
    if not isinstance(rules, list):
        raise LandError("config.schema", f"{profile.source_file}:land.evidence.names: expected {{rules: [...]}}")
    out = []
    for rule in rules:
        if not isinstance(rule, dict) or set(rule) - {"id", "pattern", "hint"} or not {"id", "pattern"} <= set(rule):
            raise LandError("config.schema", f"{profile.source_file}:land.evidence.names: bad rule {rule!r}")
        try:
            re.compile(rule["pattern"])
        except re.error as exc:
            raise LandError("config.schema", f"{profile.source_file}:land.evidence.names: {rule['id']}: {exc}") from exc
        out.append({"id": str(rule["id"]), "pattern": str(rule["pattern"]), "hint": str(rule.get("hint", ""))})
    return out


