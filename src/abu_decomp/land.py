"""`decomp land`: apply lane patches to a proof tree and run the landing gates; it never commits or pushes.

unbake owns the objective rules (setup, sync, the sync check, source audit) and `unbake land` lands inbox
submissions, which is a different job; this command only orders those public calls (through `decomp unbake`'s
isolated invoke, so the pinned tool runs) around the project's own `check` build and adds the gates that need git.

Before the apply gate each patch is carried across the renames main made since it was cut (retarget.py).

Gates, in order; the first failure stops the run and the rest are reported as skipped:
  base         the tree is clean (tracked files) and HEAD is --base
  apply        each patch applies with `git apply --3way --index`, in order. A patch that conflicts lands per file:
               every file section that applies cleanly lands and each one that does not is refused with git's reason
               (a blocking `land.file_refused` finding for that file, also in the LAND event text); a patch with no
               file landing is excluded whole. Files matching `land.union_paths`, or that the tree's gitattributes mark
               `merge=union`, never conflict: their added lines are
               merged into the tree's file as a line union (deduplicated, tree order kept, new lines appended).
               Files matching `land.regenerated_paths` (README, progress.json: no header to tell them by) are
               regenerated the same way, never patched.
               Generated files (the header `generated from config.toml; do not edit`, or the older `generated by
               unbake sync; do not edit`, in the base's copy or the patch)
               are never applied from an input: they are dropped from every patch up front (a non-blocking
               `land.regenerated` finding names them) and `unbake sync` regenerates them. With
               two or more inputs, the regenerated files go in the commit of the input whose sources caused the
               change (a `unbake sync` per prefix of the inputs finds it), the rest (README, SVG) in the last.
               function counts as converted only when every file of the patch that mentions it landed (otherwise a
               `land.function_split` finding names it). No patch landing at all fails the gate.
               Within a round a function two patches both carry lands once: a later patch's change block that an
               earlier patch already made (identical body) is a no-op, and one that rewrites a function an earlier
               patch converted differently is dropped (the first body stays) with a non-blocking
               `land.duplicate_function` finding naming both lanes; the rest of that file still lands. In a union
               file, symbol lines (`name = 0xADDR;`) merge by name: the same name at the same address is one line,
               and the same name at another address is not added and gets a `land.symbol_conflict` finding that
               carries both addresses. A symbol line splat itself rejects (the host's splat parses it alone) is not
               added either: a blocking `land.symbol_invalid` finding carries its reason, so a symbol line never
               fails `unbake setup`. A symbol line a patch removes (a move or a rename) and the tree still holds
               exactly is retracted before the patch's lines are added, and so is the tree's line at an address
               the patch
               removes and does not add again, whatever its name; other removed lines in a union file stay.
               Each input is checked against the state the earlier inputs left, before any build, and is refused
               alone (the tree goes back to before it; `land.patch_excluded` plus the reason's own finding) when
               - a symbol fact of it conflicts (`land.symbol_conflict`) or splat rejects it (`land.symbol_invalid`),
               - a fact file it changed no longer reads whole in splat, e.g. two symbols at one address
                 (`land.symbol_clash`, splat's reason names both), or
               - its commit message breaks the subject limit or the tree's commit-msg hook (`land.commit_subject`,
                 `land.commit_hook`)
  setup        `unbake setup`, every round: it answers at once when nothing it reads moved and otherwise re-extracts
               exactly the versions whose symbol facts, yaml or ROM changed (unbake stamps each version's extraction
               in the tree) and writes the generated files (`--no-make`: the check gate builds)
  check        the configured check command as `unbake-run [--work N] -- CHECK -j{j}` (N, the admit answer, caps it),
               then `unbake verify STATUS` with its exit: the project's build never calls our tools, so the verdict
               the report and sync read is recorded here (a refused verify fails the gate)
  sync_after   `unbake sync --settle` after check: writes the README the verdict moved and refuses as `sync --check`
               would unless a second sync would write nothing (10-20: sync, sync_after and sync_check were three
               serial single-core passes, 17 s each, of a 64 s warm ship; setup already writes what the first wrote)
  If setup, check or sync_after fails with more than one input landed, the failure is bisected by
  input: the tree is rebuilt with growing prefixes of the inputs (warm caches, ceil(log2 n) builds) until the first
  input whose presence breaks the build is found; that input is refused alone (`land.input_build_failed`, the build's
  reason; the result's `refused_inputs`) and the rest are built again. `attempts` lists every build.
  audit        `unbake audit --against BASE` on the final tree: the source rules the landing adds over the base
               (raw-offset, ...) are refused here; the project's own CI runs only its standalone build check, so this
               gate and sync_after are where those rules hold
  markers      no marker line (INCLUDE_ASM, NON_MATCHING, ...) added in a file no applied patch touched
  untracked_s  no untracked assembly file (every one a patch or sync produced is tracked or staged)
  standalone   no line the landing adds (patches and regenerated files, tracked or untracked) names one of our tools
               (abu_decomp.standalone): the game repo builds with make alone, so it never mentions unbake, Recipe
               Maker, Cake Taste or decomp (`land.standalone`, naming each line)
  readme       no code percentage in the README lower than at the base, unless an input declares the fall:
               `--credit-fall LANE=VERSION:BYTES:REASON` lets that lane lower the matched code bytes of README
               version VERSION (its label, or its zero-based index) by at most BYTES. When a percentage fell, the gate
               builds the inputs one prefix at a time to measure each input's own change in matched bytes; an input
               that lowers a fallen version by more than it declared (or declared nothing) fails the gate, naming the
               input and the rows. An allowed fall is a non-blocking `land.credit_fall` finding, shows in the LAND
               event and in the lane's commit body.
               The gate judges matched bytes per category, not percentages: a fall whose input leaves the matched
               code bytes unchanged and only grows the code total (bytes reclassified from matched data or label
               splits into unmatched code) passes when the lane declares it, `--reclass LANE=VERSION:+CODE/-DATA`
               (CODE = the input's growth of the version's code total, DATA = its drop of the version's matched data
               bytes); land measures both and refuses unless they equal the declaration exactly. A non-blocking
               `land.reclass` finding, `reclasses` in the result, `RECLASS` in the LAND event and a
               `Reclassification:` line in the lane's commit body record it.

`--patch LANE=PATH[:MESSAGE]`; the result's `commits` is the ready commit plan (never run here; the orchestrator
runs each of `commit_commands`; the `-- files` pathspec keeps the other lanes' staged files out of each commit).

Section `land` of the seat profile:

    "land": {
      "check": ["make", "check"],                     required; run in the tree under unbake-run, `-j{j}` added
      "jobs": ["/path/admit", "8"],                   prints N, the cap on the build's slot share; omit for no cap
      "markers": ["INCLUDE_ASM", "NON_MATCHING"],     substrings marking a stand-in line (default adds GLOBAL_ASM)
      "asm_suffix": ".s",
      "union_paths": ["versions/*/symbol_addrs.txt"], append-only fact files merged as a line union (fnmatch globs)
      "regenerated_paths": ["README.md", "progress.json"], files the tool rewrites after apply: dropped from every patch
      "readme": "README.md",
      "timeout_seconds": 7200,                        per check/jobs call
      "recipe": [{"name": "structure", "args": ["structure", "--json", "--paths", "{files}"]}],
      "recipe_suffixes": [".c", ".h"],                landed files Recipe is asked about (default .c .h .cpp)
      "actor": "land",
      "subject_limit": 72                             longest commit subject the plan may print (default 72)
    }

The commit plan always passes the project's commit rules: the subject is at most `subject_limit` characters (the
function list moves to the body, then directories are trimmed to "and N more dirs"), and every message is run through
the tree's own commit-msg hook (git's hooks path) before anything is committed; a violation is a blocking
`land.commit_subject` / `land.commit_hook` finding that fails the landing, never a refusal at commit time.

`recipe` (optional) runs the pinned Recipe Maker's proposal verbs (abu_decomp.proposals) on the landed tree after the
last gate passed: names and structure suggestions, never applied, so no lane's pending patch loses its file. The
result's `recipe` holds each step's summary and the LAND event carries it; a failing step is a non-blocking finding.

Project facts (the markers, the README, the check command) come only from that section; the tree is the argument.
"""

