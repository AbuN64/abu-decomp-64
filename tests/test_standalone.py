import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from abu_decomp import DecompError, standalone
from abu_decomp.cli import main


def git(root, *args):
    env = {"GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t"}
    return subprocess.run(["git", *args], cwd=root, env={**__import__("os").environ, **env}, check=True,
                          capture_output=True, text=True).stdout  # fmt: skip


class StandaloneTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.tree = Path(temp.name)
        git(self.tree, "init", "-q", "-b", "main")
        (self.tree / "Makefile").write_text("# One recipe per toolchain in use\nall:\n\ttrue\n")
        (self.tree / "a.h").write_text("#ifndef A_H\n#define A_H\n#endif\n")
        (self.tree / ".gitignore").write_text("/build/\n")
        git(self.tree, "add", ".")
        git(self.tree, "commit", "-q", "-m", "base")
        self.pins = mock.patch("abu_decomp.tools.pins", side_effect=DecompError("dependency.pin", "none"))
        self.pins.start()
        self.addCleanup(self.pins.stop)

    def test_every_spelling_of_a_tool_name_matches_and_plain_words_do_not(self):
        import re

        expr = re.compile(standalone.pattern(), re.I)
        for text in ("#ifndef UNBAKE_TYPES_H", "-D__UNBAKE_STDARG_GCC", "pip install cake-unbake-64", "Recipe Maker",
                     "recipemaker", "cake_taste", "abu-decomp-64", "abu_decomp.land"):  # fmt: skip
            self.assertTrue(expr.search(text), text)
        for text in ("One recipe per toolchain", "a matching decomp", "taste", "mas-n64 n64link", "Makefile"):
            self.assertFalse(expr.search(text), text)

    def test_a_clean_tree_has_no_mentions(self):
        self.assertEqual(standalone.mentions(self.tree), [])
        self.assertEqual(standalone.mentions(self.tree, against="HEAD"), [])

    def test_whole_tree_names_tracked_and_untracked_lines_but_not_ignored_ones(self):
        (self.tree / "a.h").write_text("#ifndef UNBAKE_A_H\n#define UNBAKE_A_H\n#endif\n")
        (self.tree / "new.c").write_text("/* generated by unbake */\n")
        (self.tree / "build").mkdir()
        (self.tree / "build/x.c").write_text("unbake\n")
        found = standalone.mentions(self.tree)
        self.assertEqual(sorted((f["path"], f["line"]) for f in found), [("a.h", 1), ("a.h", 2), ("new.c", 1)])

    def test_against_judges_only_added_lines(self):
        (self.tree / "a.h").write_text("#ifndef UNBAKE_A_H\n#define UNBAKE_A_H\n#endif\n")
        git(self.tree, "commit", "-q", "-am", "old mention")
        (self.tree / "a.h").write_text("#ifndef UNBAKE_A_H\n#define UNBAKE_A_H\nint x; /* cake-taste */\n#endif\n")
        (self.tree / "b.c").write_text("int y;\n")
        found = standalone.mentions(self.tree, against="HEAD")
        self.assertEqual([(f["path"], f["line"]) for f in found], [("a.h", 3)])

    def test_against_reads_only_the_untracked_files_given(self):
        (self.tree / "stray.txt").write_text("not unbake's\n")
        (self.tree / "map.json").write_text('{"by": "unbake"}\n')
        found = standalone.mentions(self.tree, against="HEAD", untracked={"map.json"})
        self.assertEqual([f["path"] for f in found], ["map.json"])
        self.assertEqual(len(standalone.mentions(self.tree, against="HEAD")), 2)

    def test_the_command_exits_one_with_a_finding(self):
        import io
        import json
        from contextlib import redirect_stdout

        (self.tree / "CONTRIBUTING.md").write_text("pip install unbake\n")
        out = io.StringIO()
        with redirect_stdout(out):
            code = main(["standalone", "--tree", str(self.tree)])
        envelope = json.loads(out.getvalue())
        self.assertEqual((code, envelope["findings"][0]["key"]), (1, "standalone.tool_named"))
        self.assertEqual(envelope["result"]["mentions"][0]["path"], "CONTRIBUTING.md")


if __name__ == "__main__":
    unittest.main()
